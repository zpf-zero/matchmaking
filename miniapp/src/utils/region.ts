export interface RegionCity {
  name: string
  /** 6 位行政区划代码，如 440300 */
  code: string
}

export interface RegionProvince {
  name: string
  /** 6 位行政区划代码，如 440000 */
  code: string
  cities: RegionCity[]
}

export const REGIONS: RegionProvince[] = RAW.map(([pc, name, cities]) => ({
  name,
  code: `${pc}0000`,
  cities: cities.map(([cc, cname]) => ({ name: cname, code: `${pc}${cc}00` })),
}))

/** 按城市编码反查省市，用于只存了 city_code 的场景（择偶要求、搜索筛选） */
export function findCityByCode(code: string): { province: RegionProvince; city: RegionCity } | null {
  if (!code) return null
  for (const province of REGIONS) {
    const city = province.cities.find((c) => c.code === code)
    if (city) return { province, city }
  }
  return null
}

/** 按省市名定位下标，找不到时退回 [0, 0] */
export function findIndexByName(province: string, city: string): [number, number] {
  const pi = REGIONS.findIndex((p) => p.name === province)
  if (pi < 0) return [0, 0]
  const ci = REGIONS[pi].cities.findIndex((c) => c.name === city)
  return [pi, ci < 0 ? 0 : ci]
}
