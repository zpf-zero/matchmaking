-- ============================================================
-- 004 邀请结算可见性：inviter_seen
--
-- 背景：SettleInvite 只写日志，邀请人不知道权益已到账，
-- 邀请动机在「结算」这一步断掉。加一列记录邀请人是否已查看
-- 某条已结算关系，供「我的」页红点与邀请页一次性提示。
--
-- 兼容 MySQL 5.6 ~ 8.x；重复执行报 1060 属预期，忽略即可。
-- ============================================================

ALTER TABLE `invite_relation`
  ADD COLUMN `inviter_seen` tinyint NOT NULL DEFAULT 0 COMMENT '邀请人是否已查看该结算 0未看 1已看';

-- 历史结算一律视为已查看：只有「本次改动之后发生的结算」才值得弹提示，
-- 否则每个有历史邀请记录的用户都会收到一次莫名的「邀请已生效」。
UPDATE `invite_relation`
  SET `inviter_seen` = 1
  WHERE `status` = 1;
